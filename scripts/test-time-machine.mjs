import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const base=process.env.TEST_BASE || 'http://127.0.0.1:3000';
await mkdir('.screenshots',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--autoplay-policy=no-user-gesture-required']});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();
const errors=[];
page.on('pageerror',err=>errors.push(err.message));
await page.goto(base,{waitUntil:'networkidle'});
await page.screenshot({path:'.screenshots/rewind-desktop.png'});
assert.equal(await page.locator('body').evaluate(el=>el.scrollWidth<=innerWidth),true,'Desktop overflow');
const slider=page.getByRole('slider',{name:'Travel through musical years'});
assert.equal(await slider.getAttribute('aria-valuenow'),'2015');
await slider.focus(); await page.keyboard.press('ArrowLeft');
assert.equal(await slider.getAttribute('aria-valuenow'),'2014');
await page.getByRole('button',{name:'Zoom in timeline'}).click();
assert.ok(await page.locator('.timeline-zoom').textContent().then(t=>t.includes('20 years')));
const bounds=await slider.boundingBox();
await page.mouse.move(bounds.x+bounds.width*.5,bounds.y+38);
await page.mouse.down();
await page.mouse.move(bounds.x+bounds.width*.8,bounds.y+38,{steps:8});
await page.mouse.up();
assert.equal(await slider.getAttribute('aria-valuenow'),'2020','Dragging must select the corresponding year');
await page.getByRole('button',{name:/1980s/}).click();
assert.equal(await page.locator('.rewind-app').getAttribute('data-era'),'1980');
assert.ok(await page.locator('.hero-artwork .format-cassette').count());
await page.getByRole('button',{name:/2000s/}).click();
assert.ok(await page.locator('.hero-artwork .format-cd').count());
await page.getByLabel('Destination year').fill('2015');
await page.getByRole('button',{name:'Travel to selected year',exact:true}).click();
await page.getByRole('button',{name:'Save The Less I Know The Better',exact:true}).click();
await page.waitForSelector('.rewind-toast');
await page.getByRole('button',{name:/My collection/}).first().click();
await page.getByRole('heading',{name:'Currents',exact:true}).waitFor();
await page.reload({waitUntil:'networkidle'});
await page.getByRole('button',{name:/My collection/}).first().click();
await page.getByRole('heading',{name:'Currents',exact:true}).waitFor();
console.log('PASS: timeline keys/zoom, cassette/CD era changes, favorites persisted across reload.');
const search = await context.request.get(`${base}/api/search?q=Radiohead%20Creep`);
const searchData=await search.json();
assert.equal(search.status(),200);
assert.ok(searchData.results.length>0);
assert.ok(searchData.results.every(t=>t.duration>60));
console.log('PASS: Full-recording search',searchData.results.slice(0,3).map(t=>({title:t.title,seconds:t.duration})));
await page.getByLabel('Search songs and artists').fill('Radiohead Creep');
await page.waitForSelector('.search-list .recording-row');
assert.ok((await page.locator('.search-list .recording-row').count())>0);
console.log('PASS: live search results rendered.');
await page.getByRole('button',{name:'Time machine',exact:true}).first().click();
await page.getByRole('button',{name:'Play 2015',exact:true}).click();
await page.waitForSelector('iframe.youtube-frame');
await page.waitForTimeout(36000);
const playback={label:await page.locator('.full-recording-heading').innerText(),timeline:await page.locator('.player-timeline').innerText(),error:await page.locator('.playback-message').textContent().catch(()=>null)};
console.log('LIVE PLAYBACK:',playback);
await page.screenshot({path:'.screenshots/rewind-playing.png'});
const elapsedText = playback.timeline.split('\n')[0];
const [minutes, seconds] = elapsedText.split(':').map(Number);
assert.ok(minutes * 60 + seconds > 30, 'Recording must actually play past 30 seconds on the public preview origin');
assert.ok(playback.label.includes('NOW PLAYING'), 'Player must be playing the full recording');
const library=await context.request.get(`${base}/api/library`).then(r=>r.json());
console.log('Actual listening memories:',library.history.length);
assert.ok(library.history.length > 0, 'Actual playback must create a dated listening memory');
await page.getByRole('button',{name:'Close video and pause playback'}).click();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'.screenshots/rewind-mobile.png'});
assert.equal(await page.locator('body').evaluate(el=>el.scrollWidth<=innerWidth),true,'Mobile overflow');
console.log('PASS: mobile has no horizontal overflow.');
console.log('Browser errors:',errors);
await browser.close();
if(errors.length) process.exitCode=1;
